import { describe, expect, it } from 'vitest'
import { LANGS } from '../../shared/messages.ts'
import { NOTIFICATION_KINDS, type Notification, type NotificationKind } from '../../shared/protocol.ts'
import { PUSH_GROUPS } from '../../shared/push.ts'
import { PUSH_SAMPLE, pushMessage, pushTemplateOf, testPushMessage } from '../../shared/push-texts.ts'
import { notificationLink, notificationText } from '../../src/lib/notifications.ts'
import { STRINGS } from '../../src/strings.ts'

/**
 * The push texts (e1-t28) are strings.ts's notification texts as templates, kept in
 * shared/push-texts.generated.ts for the Worker. `npm run push:texts` rewrites the file (this test
 * with -u); without it the test fails whenever strings.ts says something the file does not
 */

const note = (kind: NotificationKind, params: Notification['params']): Notification => ({ id: 'n1', at: 0, kind, params, read: false })

describe('push texts (e1-t28)', () => {
  it('the generated templates are up to date with strings.ts', async () => {
    const out: Record<string, unknown> = {}
    for (const lang of LANGS) {
      const t = STRINGS[lang]
      const kinds: Record<string, string> = {}
      for (const kind of NOTIFICATION_KINDS) kinds[kind] = pushTemplateOf(notificationText(t, note(kind, PUSH_SAMPLE)))
      out[lang] = { title: lang.startsWith('zh') ? t.appNameZh : t.appNameEn, test: t.push.testBody, kinds }
    }
    const file =
      '// Generated by `npm run push:texts` from src/strings.ts (tests/presentation/push-texts.test.ts): do not edit by hand\n' +
      "import type { PushTexts } from './push-texts.ts'\n\n" +
      `export const PUSH_TEXTS: PushTexts = ${JSON.stringify(out, null, 2)}\n`
    await expect(file).toMatchFileSnapshot('../../shared/push-texts.generated.ts')
  })

  const samples: Notification['params'][] = [
    { username: 'amy', challengeId: 'c1', tableId: 't1', number: 3, matchId: 'm1', pairId: 'p1', boardId: 'b1' },
    { username: '王小美', name: '自然制', slug: 'natural', title: '首攻的原則', profile: '甲隊', gb: 8.4, postId: 'p9', commentId: 'c2' },
    { username: 'ben', slug: 'precision', postId: 'p9' },
    {},
  ]

  it('says what the bell says, in every language, and leads to the same page', () => {
    for (const lang of LANGS) {
      for (const kind of NOTIFICATION_KINDS) {
        for (const params of samples) {
          const n = note(kind, params)
          const push = pushMessage(n, lang, { forum: true })
          expect(push.body, `${lang} ${kind}`).toBe(notificationText(STRINGS[lang], n))
          expect(push.url).toBe(notificationLink(n, { forum: true }))
          expect(push.title).toBe(lang.startsWith('zh') ? '淡江牌桌' : 'TKU BridgeTable')
          expect(push.tag).toBe('n1')
        }
      }
    }
    expect(pushMessage(note('forumReply', { postId: 'p1' }), 'zh').url).toContain('/forum/p/p1')
  })

  it('never reads a placeholder out of a name', () => {
    expect(pushMessage(note('challengeInvited', { username: '{title}' }), 'zh').body).toBe('{title} 邀請你參加挑戰')
  })

  it('keeps a long body short', () => {
    const body = pushMessage(note('forumReply', { username: 'amy', title: 'x'.repeat(2000), postId: 'p' }), 'en').body
    expect(body.length).toBeLessThanOrEqual(300)
    expect(body.endsWith('…')).toBe(true)
  })

  it('has a test push in every language', () => {
    for (const lang of LANGS) expect(testPushMessage(lang).body).toBe(STRINGS[lang].push.testBody)
  })

  it('puts every kind in exactly one group of the push settings', () => {
    const grouped = Object.values(PUSH_GROUPS).flat()
    expect([...grouped].sort()).toEqual([...NOTIFICATION_KINDS].sort())
  })
})
