/** A player's name as shown: a robot by its kind in the viewer's language */
export const playerName = (t: Strings, user: PublicUser) =>
  user.robot ? t.robots[user.robotKind ?? 'tku'] : user.username

/** Where a board was played, as lists show it: its table, a challenge, or practice (§5.11) */
export const boardPlace = (t: Strings, b: { mode?: TableMode; tableNumber: number }) =>
  b.mode === 'challenge' ? t.challenge : b.mode === 'practice' ? t.practice : t.tableName(b.tableNumber)
